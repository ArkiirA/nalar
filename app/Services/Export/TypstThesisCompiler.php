<?php

namespace App\Services\Export;

use App\Models\Chapter;
use App\Models\Project;

class TypstThesisCompiler
{
    /**
     * Compile an entire thesis project into complete Typst markup.
     * Follows Universitas Gunadarma / Indonesian S1 standard formatting.
     */
    public function compile(Project $project): string
    {
        $profile = $project->guideline_profile ?? [];
        $formatting = $profile['formatting'] ?? [];
        $margins = $formatting['margins'] ?? ['top' => '4 cm', 'bottom' => '3 cm', 'left' => '4 cm', 'right' => '3 cm'];

        $top = $margins['top'] ?? '4 cm';
        $bottom = $margins['bottom'] ?? '3 cm';
        $left = $margins['left'] ?? '4 cm';
        $right = $margins['right'] ?? '3 cm';

        $font = $formatting['font_family'] ?? 'Times New Roman';
        $fontSize = $formatting['font_size'] ?? '12pt';

        $typst = [];

        // 1. Page & Layout Setup
        $typst[] = "// Generated by Nalar Typst Thesis Compiler (laporan-generator-thesis)";
        $typst[] = "#set page(";
        $typst[] = "  paper: \"a4\",";
        $typst[] = "  margin: (top: {$top}, bottom: {$bottom}, left: {$left}, right: {$right}),";
        $typst[] = "  numbering: \"1\",";
        $typst[] = ")";
        $typst[] = "#set text(font: \"{$font}\", size: {$fontSize}, lang: \"id\")";
        $typst[] = "#set par(justify: true, leading: 1.5em, first-line-indent: 1cm)";
        $typst[] = "#set heading(numbering: \"1.1\")";
        $typst[] = "";

        // 2. Cover / Title Block
        $projectTitle = $this->escapeTypst($project->title);
        $authorName = $this->escapeTypst($project->user->name ?? 'Mahasiswa');
        $university = $this->escapeTypst($profile['university'] ?? 'Universitas Gunadarma');

        $typst[] = "#align(center)[";
        $typst[] = "  #v(2cm)";
        $typst[] = "  #text(size: 16pt, weight: \"bold\")[#upper(\"{$projectTitle}\")]";
        $typst[] = "  #v(3cm)";
        $typst[] = "  #text(size: 12pt)[SKRIPSI / TUGAS AKHIR]";
        $typst[] = "  #v(4cm)";
        $typst[] = "  #text(size: 12pt, weight: \"bold\")[{$authorName}]";
        $typst[] = "  #v(2cm)";
        $typst[] = "  #text(size: 12pt, weight: \"bold\")[#upper(\"{$university}\")]";
        $typst[] = "  #v(1cm)";
        $typst[] = "  #text(size: 11pt)[#datetime.today().display(\"[year]\")]";
        $typst[] = "]";
        $typst[] = "#pagebreak()";
        $typst[] = "";

        // 3. Chapters & Sections Content
        $rootChapters = $project->rootChapters()->with('sections')->orderBy('order')->get();

        foreach ($rootChapters as $index => $chapter) {
            $chapterNum = $index + 1;
            $chapterTitle = $this->cleanChapterTitle($chapter->title);

            $typst[] = "#pagebreak(weak: true)";
            $typst[] = "= {$chapterTitle}";
            $typst[] = "";

            if (!empty($chapter->content)) {
                $typst[] = $this->convertTiptapToTypst($chapter->content);
                $typst[] = "";
            }

            foreach ($chapter->sections as $section) {
                $sectionTitle = $this->cleanSectionTitle($section->title);
                $typst[] = "== {$sectionTitle}";
                $typst[] = "";

                if (!empty($section->content)) {
                    $typst[] = $this->convertTiptapToTypst($section->content);
                    $typst[] = "";
                }
            }
        }

        // ponytail: raw Typst markup generation; add CLI subprocess invocation when typst binary is provisioned on host
        return implode("\n", $typst);
    }

    /**
     * Convert Tiptap JSON document structure to Typst syntax.
     *
     * @param array<string, mixed>|null $content
     */
    public function convertTiptapToTypst(?array $content): string
    {
        if (empty($content) || !isset($content['content']) || !is_array($content['content'])) {
            return '';
        }

        $lines = [];

        foreach ($content['content'] as $node) {
            $type = $node['type'] ?? '';

            switch ($type) {
                case 'paragraph':
                    $text = $this->extractInlineFormattedText($node);
                    if (trim($text) !== '') {
                        $lines[] = $text;
                        $lines[] = "";
                    }
                    break;

                case 'heading':
                    $level = $node['attrs']['level'] ?? 1;
                    $prefix = str_repeat('=', max(1, min(4, $level)));
                    $text = $this->extractInlineFormattedText($node);
                    $lines[] = "{$prefix} {$text}";
                    $lines[] = "";
                    break;

                case 'bulletList':
                    if (isset($node['content']) && is_array($node['content'])) {
                        foreach ($node['content'] as $listItem) {
                            $text = $this->extractInlineFormattedText($listItem);
                            $lines[] = "- {$text}";
                        }
                        $lines[] = "";
                    }
                    break;

                case 'orderedList':
                    if (isset($node['content']) && is_array($node['content'])) {
                        foreach ($node['content'] as $listItem) {
                            $text = $this->extractInlineFormattedText($listItem);
                            $lines[] = "+ {$text}";
                        }
                        $lines[] = "";
                    }
                    break;

                case 'figureCaption':
                    $text = $this->extractInlineFormattedText($node);
                    $lines[] = "#align(center)[#text(style: \"italic\")[{$text}]]";
                    $lines[] = "";
                    break;

                case 'table':
                    $lines[] = $this->convertTableToTypst($node);
                    $lines[] = "";
                    break;
            }
        }

        return implode("\n", $lines);
    }

    /**
     * Convert Tiptap table structure into Typst #table(...) syntax.
     *
     * @param array<string, mixed> $tableNode
     */
    private function convertTableToTypst(array $tableNode): string
    {
        $rows = $tableNode['content'] ?? [];
        if (empty($rows)) {
            return '';
        }

        $cols = count($rows[0]['content'] ?? []);
        $out = ["#table("];
        $out[] = "  columns: {$cols},";
        $out[] = "  align: (col, row) => if row == 0 { center + horizon } else { left + horizon },";

        foreach ($rows as $rowIndex => $row) {
            $cells = $row['content'] ?? [];
            foreach ($cells as $cell) {
                $cellText = $this->extractInlineFormattedText($cell);
                $isHeader = ($cell['type'] ?? '') === 'tableHeader';

                if ($isHeader) {
                    $out[] = "  table.header([*{$cellText}*]),";
                } else {
                    $out[] = "  [{$cellText}],";
                }
            }
        }

        $out[] = ")";
        return implode("\n", $out);
    }

    /**
     * Extract and format inline marks (bold, italic, strike, code).
     *
     * @param array<string, mixed> $node
     */
    private function extractInlineFormattedText(array $node): string
    {
        $text = '';

        if (isset($node['text'])) {
            $raw = $this->escapeTypst($node['text']);
            $marks = $node['marks'] ?? [];

            foreach ($marks as $mark) {
                $markType = $mark['type'] ?? '';
                if ($markType === 'bold') {
                    $raw = "*{$raw}*";
                } elseif ($markType === 'italic') {
                    $raw = "_{$raw}_";
                } elseif ($markType === 'code') {
                    $raw = "`{$raw}`";
                }
            }

            return $raw;
        }

        if (isset($node['content']) && is_array($node['content'])) {
            foreach ($node['content'] as $child) {
                $text .= $this->extractInlineFormattedText($child);
            }
        }

        return $text;
    }

    private function cleanChapterTitle(string $title): string
    {
        return $this->escapeTypst(preg_replace('/^(BAB\s+[0-9IVXLCDM]+\s*|^\d+\.\s*)/i', '', $title));
    }

    private function cleanSectionTitle(string $title): string
    {
        return $this->escapeTypst(preg_replace('/^\d+(\.\d+)*\s*/', '', $title));
    }

    private function escapeTypst(string $text): string
    {
        return str_replace(['#', '$', '@', '\\'], ['\\#', '\\$', '\\@', '\\\\'], $text);
    }
}
